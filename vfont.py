# ------------------------------------------------------------------ engine
# Advance width = glyph width at that size + tracking, exactly as
# specified: the glyph's drawn width (its widest x coordinate, in
# glyph units, scaled by size/80) plus a 5-unit side bearing. A space
# is 0.35*size. This keeps advances honest for every glyph -- a wide
# 'M' advances more than a narrow 'i', and no glyph can ever overlap
# its neighbour, whatever its shape. Typical results: capitals
# ~0.75*size, lowercase ~0.65*size, digits ~0.75*size, narrow
# ~0.44*size, wide ~0.80*size.
_TRACK_UNITS = 5.0
_SPACE_FRAC = 0.35


def _strokes(font, ch):
    """Resolve a glyph to a list of (weight, points) strokes.

    font='sans' strokes get weight 'T' (uniform); font='serif' uses
    the stored weights. A serif glyph missing from SERIF falls back
    to the SANS shape drawn thick; any unknown char renders '?'.
    Unknown chars in SANS also fall back to '?'.
    """
    if font == 'serif':
        g = SERIF.get(ch)
        if g is not None:
            return g
        g = SANS.get(ch)
        if g is not None:
            return [('T', pts) for pts in g]
        return SERIF['?']
    g = SANS.get(ch)
    if g is not None:
        return [('T', pts) for pts in g]
    return [('T', pts) for pts in SANS['?']]


def _extent_units(font, ch):
    """Widest x coordinate of the glyph (glyph units), 0 for space."""
    mx = 0
    for _w, pts in _strokes(font, ch):
        for (x, _y) in pts:
            if x > mx:
                mx = x
    return mx


# Cache of per-glyph extents: {font: {ch: max-x units}}.
_EXTENT = {'sans': {}, 'serif': {}}


def _adv_px(ch, size, font='sans'):
    """Advance width of one glyph in px at the given size: the glyph's
    drawn width plus a fixed side bearing (tracking)."""
    if ch == ' ':
        return _SPACE_FRAC * size
    cache = _EXTENT[font]
    ext = cache.get(ch)
    if ext is None:
        ext = _extent_units(font, ch)
        cache[ch] = ext
    return (ext + _TRACK_UNITS) * size / 80.0


def _widths(size, font='sans'):
    """(sans stroke width, serif thick width, serif thin width) in px."""
    w_sans = max(1, int(round(size * 0.14)))
    w_thick = max(1, int(round(size * 0.16)))
    w_thin = max(1, int(round(size * 0.08)))
    return w_sans, w_thick, w_thin


def _draw_stroke(pg, pts, ox, oy, k, w, col, bold):
    """Draw one polyline stroke. (ox, oy) = glyph origin in logical px
    (floats), k = px per glyph unit. Joints are rounded with discs."""
    if not pts:
        return
    xy = [(ox + x * k, oy + y * k) for (x, y) in pts]
    offs = (0, 1) if bold else (0,)
    if len(xy) == 1:
        # Single-point stroke (dot, i-dot, full stop): a filled disc.
        r = max(1, w // 2)
        for dx in offs:
            pg.disc(int(round(xy[0][0])) + dx, int(round(xy[0][1])), r, col)
        return
    for dx in offs:
        for (x0, y0), (x1, y1) in zip(xy, xy[1:]):
            pg.line(int(round(x0)) + dx, int(round(y0)),
                    int(round(x1)) + dx, int(round(y1)), col, t=w)
        if w >= 2:
            # Round the joints (and the stroke ends).
            r = w // 2
            for (x0, y0) in xy:
                pg.disc(int(round(x0)) + dx, int(round(y0)), r, col)


def draw_vtext(pg, x, y, txt, size, col, font='sans', bold=False):
    """Render text at (x, y) = top-left, size = cap height in px.
    Returns the total width in px. Unknown chars render as '?'."""
    if size <= 0:
        return 0
    k = size / 80.0
    w_sans, w_thick, w_thin = _widths(size, font)
    cx = float(x)
    for ch in txt:
        if ch in '\n\t':
            ch = ' '
        adv = _adv_px(ch, size, font)
        if ch != ' ':
            for weight, pts in _strokes(font, ch):
                if font == 'serif':
                    w = w_thick if weight == 'T' else w_thin
                else:
                    w = w_sans
                _draw_stroke(pg, pts, cx, float(y), k, w, col, bold)
        cx += adv
    return int(round(cx - x))


def vtext_w(txt, size, font='sans', bold=False):
    """Advance width in px of txt at size (same metrics as draw_vtext)."""
    if size <= 0:
        return 0
    total = 0.0
    for ch in txt:
        if ch in '\n\t':
            ch = ' '
        total += _adv_px(ch, size, font)
    return int(round(total))


def vwrap(txt, size, maxw, font='sans', bold=False):
    """Greedy word wrap; returns a list of lines fitting maxw px."""
    lines = []
    for chunk in txt.split("\n"):
        words = chunk.split(" ")
        cur = ""
        for wd in words:
            trial = (cur + " " + wd).strip()
            if vtext_w(trial, size, font, bold) <= maxw or not cur:
                cur = trial
            else:
                lines.append(cur)
                cur = wd
        if cur:
            lines.append(cur)
    return lines


def vpara(pg, x, y, txt, size, col, maxw, lh=None, font='sans', bold=False,
          max_lines=None):
    """Draw a wrapped paragraph; returns the y just below the last line."""
    if lh is None:
        lh = int(size * 1.35)
    lines = vwrap(txt, size, maxw, font, bold)
    if max_lines is not None:
        lines = lines[:max_lines]
    for ln in lines:
        draw_vtext(pg, x, y, ln, size, col, font=font, bold=bold)
        y += lh
    return y


def vcentre(pg, cx, y, txt, size, col, font='sans', bold=False):
    """Draw text centred on cx."""
    draw_vtext(pg, cx - vtext_w(txt, size, font, bold) // 2, y, txt, size,
               col, font=font, bold=bold)


def vfit_scale(txt, maxw, s_hi, s_lo, font='sans', bold=False):
    """Largest size in [s_lo, s_hi] at which txt fits maxw (step 0.25)."""
    s = float(s_hi)
    lo = float(s_lo)
    while s > lo and vtext_w(txt, s, font, bold) > maxw:
        s -= 0.25
    return max(s, lo)
